<?php
echo "<h2>Операторы PHP</h2>";

$x = 10;
$y = 5;

// Операторы сравнения 
echo "<h3>Операторы сравнения</h3>";
echo "x = $x, y = $y<br>";

echo "x > y: ";
var_dump($x > $y); // проверяем: больше ли x чем y

echo "x == y: ";
var_dump($x == $y); // проверяем: равны ли x и y

echo "x != y: ";
var_dump($x != $y); // проверяем: не равны ли x и y


// Условный оператор if
echo "<h3>if / else</h3>";

if ($x > $y) {
    echo "x больше y<br>";
} else {
    echo "x меньше или равно y<br>";
}


// Тернарный оператор
echo "<h3>Тернарный оператор</h3>";

$result = ($x == 10) ? "x равно 10" : "x не равно 10";
echo $result . "<br>";
?>
