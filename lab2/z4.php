<?php
echo "<h2>Пользовательские функции в PHP</h2>";

/* Функция без параметров — возвращает число */
function getNumber() {
    $number = 777; // локальная переменная внутри функции
    return $number; // возвращаем значение
}

echo "<h3>Функция без параметров</h3>";
echo "Результат функции: " . getNumber() . "<br><br>";

/* Функция с параметрами — принимает два числа и возвращает результат */
function multiply($a, $b) {
    return $a * $b; // умножаем параметры
}

echo "<h3>Функция с параметрами</h3>";
echo "6 × 7 = " . multiply(6, 7) . "<br><br>";

/* Использование встроенной функции date() — определяем приветствие по времени */
function greeting() {
    $hour = date("H"); // получаем текущий час

    if ($hour >= 5 && $hour <= 11) return "Доброе утро!";
    if ($hour >= 12 && $hour <= 16) return "Здравствуйте!";
    if ($hour >= 17 && $hour <= 23) return "Добрый вечер!";
    return "Доброй ночи!";
}

echo "<h3>Использование встроенной функции</h3>";
echo greeting() . "<br><br>";

/* Локальные и глобальные переменные — внутри функции переменная своя */
$a = 100; // глобальная переменная

function showLocal() {
    $a = 50; // локальная переменная, не влияет на глобальную
    echo "Локальная переменная внутри функции: $a<br>";
}

echo "<h3>Локальные и глобальные переменные</h3>";
showLocal();
echo "Глобальная переменная вне функции: $a<br><br>";

/* Инструкция global — позволяет работать с глобальными переменными */
$x = 10;
$y = 5;

function addGlobal() {
    global $x, $y; // подключаем глобальные переменные
    $y = $x + $y;  // изменяем глобальную переменную
}

addGlobal();

echo "<h3>Инструкция global</h3>";
echo "После вызова функции y = $y<br><br>";

/* Статическая переменная — сохраняет значение между вызовами функции */
function counter() {
    static $count = 0; // значение не сбрасывается при повторном вызове
    $count++;
    echo "Вызов № $count<br>";
}

echo "<h3>Статические переменные</h3>";
for ($i = 0; $i < 10; $i++) {
    counter(); // каждый вызов увеличивает счётчик
}
?>
