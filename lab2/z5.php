<?php
echo "<h2>Массивы</h2>";

// индексный массив — специально несортированный
$fruits = ["красный", "синий", "зелёный"];
sort($fruits); // сортировка по алфавиту

echo "<h3>Индексный массив</h3>";
echo "Первый элемент: " . $fruits[0] . "<br>";
echo "Второй элемент: " . $fruits[1] . "<br>";

echo "Перебор массива:<br>";
foreach ($fruits as $fruit) {
    echo "- $fruit<br>";
}

// ассоциативный массив — значения специально перемешаны
echo "<h3>Ассоциативный массив</h3>";

$user = [
    "name" => "Ульяна",
    "age" => 18,
    "city" => "Гродно"
];

asort($user); // сортировка по значениям

foreach ($user as $key => $value) {
    echo "$key: $value<br>";
}

// многомерный массив — имена в разном порядке
echo "<h3>Многомерный массив</h3>";

$students = [
    ["Яна", 21],
    ["Андрей", 19],
    ["Кирилл", 22]
];

usort($students, function($a, $b) { // сортировка по имени
    return strcmp($a[0], $b[0]);
});

foreach ($students as $s) {
    echo "Имя: " . $s[0] . ", возраст: " . $s[1] . "<br>";
}
?>
