<?php
echo "<h2>Операции PHP</h2>";

$a = 10;
$b = 3;

echo "<h3>Арифметические операции</h3>";
echo "a + b = " . ($a + $b) . "<br>"; // сложение
echo "a - b = " . ($a - $b) . "<br>"; // вычитание
echo "a * b = " . ($a * $b) . "<br>"; // умножение
echo "a / b = " . ($a / $b) . "<br>"; // деление
echo "a % b = " . ($a % $b) . "<br>"; // остаток от деления


echo "<h3>Операции присваивания</h3>";

echo "<b>Присваивание внутри выражения</b><br>";
$a = ($b = 4) + 5;
// $b = 4
// затем 4 + 5 = 9
echo "a = (b = 4) + 5 → a = 9, b = 4<br><br>";


echo "<b>Комбинированное присваивание</b><br>";
// было: a = 9
$a += 5; 
// действие: a = a + 5 → 9 + 5 = 14
echo "a += 5 → 9 + 5 = 14<br><br>";

// было: a = 14
$a -= 5;
// действие: a = a - 5 → 14 - 5 = 9
echo "a -= 5 → 14 - 5 = 9<br><br>";


// было: a = 9
$a *= 2;
// действие: a = a * 2 → 9 * 2 = 18
echo "a *= 2 → 9 * 2 = 18<br><br>";


// было: a = 18
$a /= 2;
// действие: a = a / 2 → 18 / 2 = 9
echo "a /= 2 → 18 / 2 = 9<br><br>";


// было: a = 9
$a %= 2;
// действие: a = a % 2 → остаток от 9 / 2 = 1
echo "a %= 2 → 9 % 2 = 1<br><br>";


echo "<h3>Строковые операции</h3>";

$a = "Hello";
$b = "World";

// конкатенация строк
$c = $a . " " . $b; // объединение строк
echo "c = a . ' ' . b → $c<br>";

// конкатенация с присваиванием
$c .= "!"; // добавление к строке
echo "c .= '!' → $c<br>";


echo "<h3>Логические операции</h3>";

$a = true;
$b = false;

// логическое И
echo "a AND b → " . (($a and $b) ? "true" : "false") . "<br>";
echo "a && b → " . (($a && $b) ? "true" : "false") . "<br><br>";

// логическое ИЛИ
echo "a OR b → " . (($a or $b) ? "true" : "false") . "<br>";
echo "a || b → " . (($a || $b) ? "true" : "false") . "<br><br>";

// исключающее ИЛИ
echo "a XOR b → " . (($a xor $b) ? "true" : "false") . "<br><br>";

// инверсия
echo "!a → " . ((!$a) ? "true" : "false") . "<br>";

echo "<h3>Операции сравнения</h3>";

$a = 10;
$b = 5;

echo "a == b → " . (($a == $b) ? "true" : "false") . "<br>";   // равно
echo "a != b → " . (($a != $b) ? "true" : "false") . "<br>";   // не равно
echo "a > b  → " . (($a > $b)  ? "true" : "false") . "<br>";   // больше
echo "a < b  → " . (($a < $b)  ? "true" : "false") . "<br>";   // меньше
echo "a >= b → " . (($a >= $b) ? "true" : "false") . "<br>";   // больше или равно
echo "a <= b → " . (($a <= $b) ? "true" : "false") . "<br>";   // меньше или равно

// строгое сравнение
echo "a === b → " . (($a === $b) ? "true" : "false") . "<br>"; // строго равно (тип + значение)
echo "a !== b → " . (($a !== $b) ? "true" : "false") . "<br>"; // строго не равно