<?php
echo "<h2>Строковый тип данных</h2>";

// строка для примеров
$str = "Hello, world!";

// длина строки
echo "Длина строки: " . strlen($str) . "<br>";

// перевод в верхний регистр
echo "В верхнем регистре: " . strtoupper($str) . "<br>";

// перевод в нижний регистр
echo "В нижнем регистре: " . strtolower($str) . "<br>";

// замена части строки
echo "Замена 'world' на 'PHP': " . str_replace("world", "PHP", $str) . "<br>";

// вырезание части строки
echo "Первые 5 символов: " . substr($str, 0, 5) . "<br>";

// поиск подстроки
echo "Позиция 'world': " . strpos($str, "world") . "<br>";


// сортировка строк — пример массива строк
echo "<h3>Сортировка строк</h3>";

$words = ["Минск", "Брест", "Гродно"]; // массив строк
sort($words); // сортировка по алфавиту

echo "Отсортированные строки:<br>";
foreach ($words as $w) { // вывод строк
    echo "- $w<br>";
}
?>
